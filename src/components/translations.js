/**
 * Translate a semantic key or an exact English UI phrase.
 * Unknown text is returned unchanged. Dynamic farm names,
 * user-entered notes and numerical values remain untouched.
 */
export function getTranslation(language, key) {
  const lang = UI_TRANSLATIONS[language] ? language : "en";
  const semanticDictionary =
    CORE_TRANSLATIONS[lang] || CORE_TRANSLATIONS.en;
  const phraseDictionary =
    UI_TRANSLATIONS[lang] || UI_TRANSLATIONS.en;

  if (
    Object.prototype.hasOwnProperty.call(
      semanticDictionary,
      key
    )
  ) {
    return semanticDictionary[key];
  }

  if (
    Object.prototype.hasOwnProperty.call(
      phraseDictionary,
      key
    )
  ) {
    return phraseDictionary[key];
  }

  return key;
}

export default getTranslation;
